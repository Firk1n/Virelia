#!/usr/bin/env node
// Reduce region-geometry.js to the twelve bounding boxes the map actually reads.
//
// The traced polygons exist so the region tool can edit them and so a region
// without a painted overlay can still be drawn as a vector outline. Neither is
// something a visitor does: at runtime the only question asked of the geometry
// is "what box do I frame?", which regions.js answers with .getBounds().
//
// So the detail stays in region-geometry.js for edit mode, and the page gets
// this instead -- the same framing, about a thousandth of the bytes.
//
//     node scripts/build-region-bounds.mjs           # write generated/region-bounds.js
//     node scripts/build-region-bounds.mjs --check   # fail if it is out of date
//
// Bounds are emitted as [[south, west], [north, east]] -- Leaflet's latLng
// order, not GeoJSON's -- because that is what L.latLngBounds() takes and the
// conversion should happen once, here, rather than on every entry click.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'region-geometry.js');
const OUTPUT = path.join(ROOT, 'generated', 'region-bounds.js');

/** Walk any GeoJSON coordinate nesting and collect [south, west, north, east]. */
function extend(box, coordinates) {
    if (typeof coordinates[0] === 'number') {
        const [lng, lat] = coordinates;
        box[0] = Math.min(box[0], lat);
        box[1] = Math.min(box[1], lng);
        box[2] = Math.max(box[2], lat);
        box[3] = Math.max(box[3], lng);
        return box;
    }
    for (const child of coordinates) extend(box, child);
    return box;
}

function boundsOf(geometry) {
    const box = extend([Infinity, Infinity, -Infinity, -Infinity], geometry.coordinates);
    if (!box.every(Number.isFinite)) return null;
    // Six decimals is ~10 cm on Earth and far finer than a hand-traced border
    // on a painted map; it keeps the file small without moving any frame.
    const round = (n) => Number(n.toFixed(6));
    return [[round(box[0]), round(box[1])], [round(box[2]), round(box[3])]];
}

function build() {
    const sandbox = { window: {} };
    // region-geometry.js is a plain assignment to window, not a module.
    new Function('window', fs.readFileSync(SOURCE, 'utf8')).call(sandbox, sandbox.window);
    const regions = (sandbox.window.REGION_GEOMETRY || {}).regions || {};

    const bounds = {};
    const skipped = [];
    for (const id of Object.keys(regions).sort()) {
        const box = boundsOf(regions[id]);
        if (box) bounds[id] = box;
        else skipped.push(id);
    }
    if (skipped.length) {
        console.warn('warning: no usable coordinates for ' + skipped.join(', '));
    }

    const lines = Object.keys(bounds).map(
        (id) => '    ' + JSON.stringify(id) + ': ' + JSON.stringify(bounds[id]));
    return '// Generated by scripts/build-region-bounds.mjs from region-geometry.js.\n' +
        '// Do not edit: trace borders with the region tool (?edit) and rebuild.\n' +
        '// [[south, west], [north, east]] -- Leaflet latLng order.\n' +
        'window.REGION_BOUNDS = {\n' + lines.join(',\n') + '\n};\n';
}

const wanted = build();
const check = process.argv.includes('--check');
const existing = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
const count = (wanted.match(/^    "/gm) || []).length;

if (check) {
    if (existing !== wanted) {
        console.error('generated/region-bounds.js is out of date. Run: node scripts/build-region-bounds.mjs');
        process.exit(1);
    }
    console.log('generated/region-bounds.js is current (' + count + ' regions).');
} else {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, wanted);
    const from = (fs.statSync(SOURCE).size / 1024).toFixed(0);
    const to = (Buffer.byteLength(wanted) / 1024).toFixed(1);
    console.log('Wrote generated/region-bounds.js: ' + count + ' regions, ' +
        from + ' KB -> ' + to + ' KB.');
}
